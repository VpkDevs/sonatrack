export function rhymeLabelFromIndex(index: number): string {
  const letter = String.fromCharCode(65 + (index % 26));
  const cycle = Math.floor(index / 26);
  return cycle === 0 ? letter : `${letter}${cycle + 1}`;
}

export function analyzeRhymeScheme(text: string): {
  lines: string[];
  scheme: string[];
} {
  const lines = text
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0);

  const endings = lines.map((line) => {
    const words = line.split(/\s+/);
    const lastWord = words[words.length - 1] ?? "";
    return lastWord.toLowerCase().replace(/[^a-z]/g, "");
  });

  const scheme: string[] = [];
  const families: Record<string, string> = {};
  let nextIdx = 0;

  for (const word of endings) {
    if (!word) {
      scheme.push("");
      continue;
    }

    let matchedKey: string | null = null;
    for (const [fam, words] of Object.entries(RHYME_FAMILIES)) {
      if (words.includes(word) || word.endsWith(fam)) {
        matchedKey = fam;
        break;
      }
    }

    const groupKey = matchedKey ?? word;
    if (!families[groupKey]) {
      families[groupKey] = rhymeLabelFromIndex(nextIdx++);
    }
    scheme.push(families[groupKey]);
  }

  return { lines, scheme };
}

export function findRhymes(searchWord: string): string[] | null {
  const term = searchWord.toLowerCase().trim().replace(/[^a-z]/g, "");
  if (!term) return null;

  for (const words of Object.values(RHYME_FAMILIES)) {
    if (words.includes(term)) {
      return words.filter((w) => w !== term);
    }
  }

  for (const [fam, words] of Object.entries(RHYME_FAMILIES)) {
    if (term.endsWith(fam)) {
      return words.filter((w) => w !== term);
    }
  }

  return [];
}

export interface SongSectionLike {
  name: string;
  bars: number;
  notes?: string;
}

export function calculateTotalBars(sections: readonly SongSectionLike[]): number {
  return sections.reduce(
    (acc, section) => acc + (Number.isFinite(section.bars) && section.bars > 0 ? section.bars : 0),
    0,
  );
}

export function formatStructureExport(
  sections: readonly SongSectionLike[],
): string {
  const totalBars = calculateTotalBars(sections);
  const lines = sections
    .map(
      (section, i) =>
        `[${i + 1}] ${section.name} — ${section.bars} bars${
          section.notes ? `\n    ${section.notes}` : ""
        }`,
    )
    .join("\n\n");

  return `SONG STRUCTURE\n${"=".repeat(40)}\nTotal: ${totalBars} bars\n\n${lines}`;
}

export function reorderItems<T>(
  items: readonly T[],
  fromIndex: number,
  toIndex: number,
): T[] {
  if (
    fromIndex < 0 ||
    toIndex < 0 ||
    fromIndex >= items.length ||
    toIndex >= items.length ||
    fromIndex === toIndex
  ) {
    return [...items];
  }

  const next = [...items];
  const [moved] = next.splice(fromIndex, 1);
  next.splice(toIndex, 0, moved);
  return next;
}

export function sanitizeExternalUrl(raw: string | undefined): string | null {
  if (!raw) return null;
  const trimmed = raw.trim();
  if (!trimmed) return null;

  try {
    const parsed = new URL(trimmed);
    if (parsed.protocol === "http:" || parsed.protocol === "https:") {
      return parsed.toString();
    }
    return null;
  } catch {
    return null;
  }
}

export interface ConceptGeneratorInput {
  genre: string;
  mood: string;
  bpmMin: string;
  bpmMax: string;
  theme: string;
  selectedInsts: string[];
  id?: string;
  date?: string;
  rng?: () => number;
}

export interface GeneratedConcept {
  id: string;
  date: string;
  genre: string;
  mood: string;
  theme: string;
  bpmRange: string;
  titles: string[];
  hookIdea: string;
  verseThemes: string[];
  bridgeConcept: string;
  productionNotes: string;
  referenceArtists: string[];
}

function shuffleWithRng<T>(items: readonly T[], rng: () => number): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

export function generateSongConcept(
  input: ConceptGeneratorInput,
): GeneratedConcept {
  const rng = input.rng ?? Math.random;
  const baseTheme = input.theme.trim() || "the human condition";
  const instStr =
    input.selectedInsts.length > 0
      ? input.selectedInsts.join(" and ")
      : "minimal instrumentation";
  const primaryInst = input.selectedInsts[0] ?? "drums";
  const secondaryInst = input.selectedInsts[1] ?? "synths";

  const titles = shuffleWithRng(
    [
      `${input.mood} ${baseTheme}`,
      `Beyond the ${baseTheme}`,
      `Echoes of ${input.genre}`,
      `Midnight ${instStr.split(" ")[0]}`,
      `${baseTheme} in ${input.bpmMin} BPM`,
    ],
    rng,
  ).slice(0, 3);

  const hooks = [
    `A soaring melody over heavy ${primaryInst} that resolves the tension of the verse, chanting about ${baseTheme}.`,
    `A rhythmic, driving vocal chop pattern that abruptly cuts to silence before dropping into a massive ${input.mood.toLowerCase()} chorus about ${baseTheme}.`,
    `An intimate, almost whispered confession about ${baseTheme}, surrounded by swirling ${secondaryInst}.`,
  ];

  const verses = [
    `Setting the scene: the initial realization of ${baseTheme}.`,
    `The complication: how ${input.mood.toLowerCase()} emotions twist the perspective.`,
    `The aftermath: looking back at the wreckage.`,
    `Sensory details of the environment.`,
    `A direct address to the antagonist of the story.`,
  ];

  const bridges = [
    `A sudden half-time switch up, dropping all instruments except ${input.selectedInsts[0] ?? "piano"}.`,
    `Building a chaotic wall of sound with ${instStr} that abruptly stops.`,
    `A completely different chord progression introducing a new, conflicting perspective on ${baseTheme}.`,
  ];

  const production = [
    `Keep the low-end muddy but precise. Use heavy saturation on the ${input.selectedInsts[0] ?? "lead"} to convey the ${input.mood.toLowerCase()} vibe.`,
    `Aim for a wide stereo image in the chorus. The tempo should feel pushing at ${input.bpmMax} BPM but dragging at ${input.bpmMin} BPM.`,
    `Very dry, upfront vocals. Let the ${instStr} sit wide and drowned in lush reverb to create contrast.`,
  ];

  const artists = [
    "Frank Ocean",
    "The Weeknd",
    "Billie Eilish",
    "Tame Impala",
    "Rosalía",
    "Kendrick Lamar",
    "James Blake",
    "FKA twigs",
    "Bon Iver",
    "Flume",
  ];

  const pick = <T,>(list: readonly T[]): T =>
    list[Math.floor(rng() * list.length) % list.length];

  return {
    id: input.id ?? crypto.randomUUID(),
    date: input.date ?? new Date().toISOString(),
    genre: input.genre,
    mood: input.mood,
    theme: baseTheme,
    bpmRange: `${input.bpmMin}-${input.bpmMax}`,
    titles,
    hookIdea: pick(hooks),
    verseThemes: shuffleWithRng(verses, rng).slice(0, 3),
    bridgeConcept: pick(bridges),
    productionNotes: pick(production),
    referenceArtists: shuffleWithRng(artists, rng).slice(0, 3),
  };
}
